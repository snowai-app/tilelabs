#!/usr/bin/env python3
"""Builds lib/product-words.ts from lib/product-words.src.txt (English ||| Spanish ||| Hindi ||| Chinese, a line each)
and lib/product-words.more.src.txt (English ||| Japanese ||| Korean ||| Portuguese, T-3829). Every English phrase must be in both. Never edit the .ts by hand."""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent

def read(name):
    rows = {}
    for n, line in enumerate((root / name).read_text(encoding='utf-8').splitlines(), 1):
        if not line.strip():
            continue
        parts = [p.strip() for p in line.split(' ||| ')]
        if len(parts) != 4 or not all(parts):
            sys.exit(f'{name} line {n}: needs four non-empty parts')
        if parts[0] in rows:
            sys.exit(f'{name} line {n}: duplicate {parts[0]!r}')
        rows[parts[0]] = parts[1:]
    return rows

a = read('lib/product-words.src.txt')
b = read('lib/product-words.more.src.txt')
missing = sorted(set(a) ^ set(b))
if missing:
    sys.exit('not in both files: ' + '; '.join(missing))
rows = {k: a[k] + b[k] for k in a}
out = "/* Generated by scripts/build-words.py from lib/product-words.src.txt and lib/product-words.more.src.txt. Do not edit by hand. English is the key; each value is [Spanish, Hindi, Chinese, Japanese, Korean, Portuguese]. */\n"
out += "export const PRODUCT_WORDS: Record<string, [string, string, string, string, string, string]> = " + json.dumps(rows, ensure_ascii=False, indent=1) + ";\n"
(root / 'lib/product-words.ts').write_text(out, encoding='utf-8')
print(len(rows), 'phrases')
