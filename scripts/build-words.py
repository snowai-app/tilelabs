#!/usr/bin/env python3
"""Builds lib/product-words.ts from lib/product-words.src.txt (English ||| Spanish ||| Hindi ||| Chinese, a line each). Never edit the .ts by hand."""
import json, sys, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
rows = {}
for n, line in enumerate((root / 'lib/product-words.src.txt').read_text(encoding='utf-8').splitlines(), 1):
    if not line.strip():
        continue
    parts = [p.strip() for p in line.split(' ||| ')]
    if len(parts) != 4 or not all(parts):
        sys.exit(f'line {n}: needs four non-empty parts')
    if parts[0] in rows:
        sys.exit(f'line {n}: duplicate {parts[0]!r}')
    rows[parts[0]] = parts[1:]
out = "/* Generated by scripts/build-words.py from lib/product-words.src.txt. Do not edit by hand. English is the key; each value is [Spanish, Hindi, Chinese]. */\n"
out += "export const PRODUCT_WORDS: Record<string, [string, string, string]> = " + json.dumps(rows, ensure_ascii=False, indent=1) + ";\n"
(root / 'lib/product-words.ts').write_text(out, encoding='utf-8')
print(len(rows), 'phrases')
